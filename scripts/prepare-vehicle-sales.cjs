#!/usr/bin/env node
// Usage: node scripts/prepare-vehicle-sales.cjs /absolute/path/to/reviewed-stock.json
// The input is kept outside the public repository. Only approved, current stock is exported.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { validateDealer, selectPublished } = require('../js/vehicle-sales.js');
const input = process.argv[2];
if (!input) { console.error('Provide a reviewed stock JSON file.'); process.exit(1); }
const project = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(input, 'utf8'));
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(project, 'data/cars.js'), 'utf8') + '\nthis.models = carsData;', context);
if (!Array.isArray(source.dealers) || !Array.isArray(source.listings)) throw new Error('Expected dealers and listings arrays.');
const dealers = source.dealers.filter(validateDealer).map(({ id, name, email, phone }) => ({ id, name, active: true, ...(email ? { email } : {}), ...(phone ? { phone } : {}) }));
if (new Set(dealers.map(dealer => dealer.id)).size !== dealers.length) throw new Error('Dealer IDs must be unique.');
const approved = source.listings.filter(listing => listing.status === 'published');
const publicFields = ['id','dealerId','modelId','trimName','condition','year','mileageKm','price','currency','priceIncludesVat','city','province','photos','status','publishedAt','expiresAt'];
const listings = selectPublished({ enabled: true, dealers, listings: approved }, context.models).map(listing => Object.fromEntries(publicFields.filter(key => key in listing).map(key => [key, listing[key]])));
if (listings.length !== approved.length) throw new Error('A published listing is invalid, expired, duplicated or has an inactive dealer. Nothing was written.');
const usedDealers = dealers.filter(dealer => listings.some(listing => listing.dealerId === dealer.id));
const output = '// Public, approved stock only. Generated by scripts/prepare-vehicle-sales.cjs.\nwindow.electricosVehicleSales = ' + JSON.stringify({ enabled: listings.length > 0, dealers: usedDealers, listings }, null, 4) + ';\n';
fs.writeFileSync(path.join(project, 'data/vehicle-sales.js'), output);
console.log(`Prepared ${listings.length} listings and ${usedDealers.length} dealers. Review the diff before publishing.`);
